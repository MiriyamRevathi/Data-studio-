  private records: VaderLexiconSentimentPolarityScorerTelemetryRecord[];

  constructor(initialData = VADERLEXICONSENTIMENTPOLARITYSCORER_HISTORICAL_DATA) {
    this.records = [...initialData];
  }

  public getAllRecords(): VaderLexiconSentimentPolarityScorerTelemetryRecord[] {
    return this.records;
  }

  public findById(id: string): VaderLexiconSentimentPolarityScorerTelemetryRecord | undefined {
    return this.records.find(r => r.id === id);
  }

  public findByLot(lot: string): VaderLexiconSentimentPolarityScorerTelemetryRecord | undefined {
    return this.records.find(r => r.batchLotNumber === lot);
  }

  public calculateAverageLatency(): number {
    if (this.records.length === 0) return 0;
    const sum = this.records.reduce((acc, r) => acc + r.measuredComputeLatencyMs, 0);
    return Number((sum / this.records.length).toFixed(3));
  }

  public calculateThroughputStats(): { min: number; max: number; avg: number } {
    if (this.records.length === 0) return { min: 0, max: 0, avg: 0 };
    const rates = this.records.map(r => r.recordsProcessedPerSec);
    const min = Math.min(...rates);
    const max = Math.max(...rates);
    const avg = rates.reduce((a, b) => a + b, 0) / rates.length;
    return { min, max, avg: Number(avg.toFixed(2)) };
  }

  public assessComplianceStatus(): { total: number; compliantCount: number; complianceRatePct: number } {
    const compliant = this.records.filter(r => r.complianceLevel === "Certified_A" || r.complianceLevel === "Grade_B_Acceptable");
    const rate = this.records.length > 0 ? (compliant.length / this.records.length) * 100 : 100;
    return { total: this.records.length, compliantCount: compliant.length, complianceRatePct: Number(rate.toFixed(2)) };
  }

  public filterBySeverity(severity: VaderLexiconSentimentPolarityScorerAlertSeverity): VaderLexiconSentimentPolarityScorerTelemetryRecord[] {
    return this.records.filter(r => r.alertSeverity === severity);
  }
