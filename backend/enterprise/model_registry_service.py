class ModelRegistryService:
    """Enterprise controller for ModelRegistryService operations."""

    def __init__(self, data: Optional[List[Dict[str, Any]]] = None):
        self.data = data if data is not None else MODELREGISTRYSERVICE_CATALOG
        self.initialized_at = time.time()

    def get_all(self) -> List[Dict[str, Any]]:
        return self.data

    def find_by_id(self, record_id: str) -> Optional[Dict[str, Any]]:
        for item in self.data:
            if item.get('id') == record_id:
                return item
        return None

    def compute_performance_metrics(self) -> Dict[str, float]:
        if not self.data:
            return {'mean_latency': 0.0, 'mean_throughput': 0.0, 'mean_accuracy': 0.0}
        latencies = [x['latency_ms'] for x in self.data]
        throughputs = [x['throughput_rps'] for x in self.data]
        accuracies = [x['accuracy_score'] for x in self.data]
        return {
            'mean_latency': round(sum(latencies) / len(latencies), 3),
            'mean_throughput': round(sum(throughputs) / len(throughputs), 2),
            'mean_accuracy': round(sum(accuracies) / len(accuracies), 4),
        }

    def filter_by_status(self, status: str) -> List[Dict[str, Any]]:
        return [x for x in self.data if x.get('status') == status]

    def validate_compliance(self) -> Dict[str, Any]:
        total = len(self.data)
        compliant = sum(1 for x in self.data if x.get('compliance_grade') in ['GRADE_A_ENTERPRISE', 'GRADE_B_REVIEWED'])
        return {
            'total_inspected': total,
            'compliant_records': compliant,
            'compliance_pct': round((compliant / total * 100) if total > 0 else 100.0, 2),
            'timestamp_iso': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())
        }

